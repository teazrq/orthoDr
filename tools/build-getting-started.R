# Run from the package root, after installing the corresponding package build.
# knitr is a documentation tool, not a package runtime dependency.
if (!requireNamespace("knitr", quietly = TRUE))
  stop("Install knitr in your usual R user library: install.packages('knitr')")

build_guide <- function() {
  source_file <- "inst/examples/getting-started.R"
  output_file <- "inst/examples/getting-started.md"
  version <- read.dcf("DESCRIPTION", fields = "Version")[[1L]]
  if (as.character(utils::packageVersion("orthoDr")) != version)
    stop("Install this package version before building its guide")

  previous <- knitr::opts_chunk$get()
  previous_knit <- knitr::opts_knit$get()
  on.exit(knitr::opts_chunk$restore(previous), add = TRUE)
  on.exit(knitr::opts_knit$restore(previous_knit), add = TRUE)
  # Save figures once under man/figures, with links relative to the Markdown.
  knitr::opts_knit$set(base.dir = normalizePath(dirname(output_file), winslash = "/"))
  knitr::opts_chunk$set(
    collapse = TRUE, comment = "#>", error = FALSE,
    dev = "png", dpi = 120, fig.width = 7, fig.height = 4.5,
    fig.path = "../../man/figures/getting-started-"
  )
  rmd <- knitr::spin(text = readLines(source_file, warn = FALSE), knit = FALSE)
  body <- knitr::knit(text = rmd, envir = new.env(parent = globalenv()), quiet = TRUE)
  provenance <- c(
    "<!-- Generated by tools/build-getting-started.R; edit getting-started.R. -->",
    paste0("<!-- Source MD5: ", unname(tools::md5sum(source_file)), " -->"),
    paste0("<!-- orthoDr ", version, "; R ", getRversion(), "; ", Sys.Date(), " -->"),
    ""
  )
  writeLines(c(provenance, body), output_file, useBytes = TRUE)
  cat("Generated", output_file, "\n")
}

build_guide()
